/** Unsplash kaynak URL'i. Next/Image zaten yeniden boyutlandırıyor; burada
 *  yalnızca gereğinden büyük orijinali indirmemek için üst sınır veriyoruz. */
function img(id: string, width = 1400): string {
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${width}&q=80`;
}

/** Aranan kaydı bulur, yoksa hemen patlar — sessiz `undefined` sızmasın. */
function mustFind<T>(items: readonly T[], predicate: (item: T) => boolean, label: string): T {
  const found = items.find(predicate);
  if (!found) throw new Error(`mockData: "${label}" bulunamadı.`);
  return found;
}

