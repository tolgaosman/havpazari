function brandRef(slug: string): BrandRef {
  const { id, name } = mustFind(brands, (b) => b.slug === slug, `marka:${slug}`);
  return { id, name, slug };
}

function categoryRef(slug: string): CategoryRef {
  const { id, name } = mustFind(categories, (c) => c.slug === slug, `kategori:${slug}`);
  return { id, name, slug };
}

